#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const index = require('../index.js');
const mcp = require('./mcp.js');

const VERSION = require('../package.json').version;

function log(icon, message) {
  console.log(`  ${icon} ${message}`);
}

function installModuleFiles(agent) {
  const agentsDir = path.join(agent.baseDir(), agent.moduleDir);
  const files = index.getAgentFiles();

  if (!fs.existsSync(agentsDir)) {
    fs.mkdirSync(agentsDir, { recursive: true });
  }

  for (const [relativePath, sourcePath] of Object.entries(files)) {
    const destPath = path.join(agentsDir, relativePath);
    fs.mkdirSync(path.dirname(destPath), { recursive: true });
    fs.copyFileSync(sourcePath, destPath);
  }

  const templatesDir = path.join(agentsDir, 'templates');
  if (!fs.existsSync(templatesDir)) {
    fs.mkdirSync(templatesDir, { recursive: true });
  }
  for (const [name, sourcePath] of Object.entries(index.getTemplateFiles())) {
    fs.copyFileSync(sourcePath, path.join(templatesDir, name));
  }

  writeConfig(agentsDir);
  generateIndex(agentsDir, agent);

  return Object.keys(files).length;
}

